// web-push — lock-screen notifications for the installed app (v10.48.0, TD-22).
//
// Three callers, one function (deployed --no-verify-jwt; every mode checks its own auth):
//   • POST {mode:'key'}   member JWT → the VAPID public key the browser subscribes with.
//   • POST {mode:'test'}  member JWT → a test notification to the caller's own devices,
//                         with each push service's answer, so a device is proven end to end.
//   • POST ?mode=dispatch pg_cron (x-cron-secret, checked against Vault) or the service key:
//       1. for every household with a subscribed device, raise the notifications the APP
//          would raise (the bundled lib/notifications.ts rules, serverEngine) into the
//          shared `notifications` table, so nobody needs the app open;
//       2. push every unread, not-yet-pushed P1 notification to the household's devices,
//          subject to each device's own switches and quiet hours (web-push-rules.ts);
//       3. stamp `pushed_at`, log each attempt in `push_deliveries`, and retire devices the
//          push service reports gone (404/410).
//
// Keys: the VAPID key pair is generated here on first use and kept in Vault
// (web_push_vapid); the cron secret is generated by the migration, also in Vault. No
// person ever sees or handles either.
import { createClient, type SupabaseClient } from 'https://esm.sh/@supabase/supabase-js@2.45.0';
import { env, json, corsHeaders } from '../_shared/whatsapp.ts';
import { isServiceCaller } from '../_shared/service-auth.ts';
import { generateVapidKeys, sendWebPush, isPushEndpoint, type VapidKeys } from '../_shared/web-push.ts';
import {
  skipReason, payloadFor, testPayload, type SubscriptionRow, type NotificationRow,
} from '../_shared/web-push-rules.ts';
import { loadHouseholdRows } from '../_shared/agent/householdLoader.ts';
import { notificationsOnServer } from '../_shared/agent/engine.ts';

const VAPID_SUBJECT = 'https://vyact.app';
/** Rows older than this are never pushed (a device that was offline gets today's news, not last week's). */
const PUSH_WINDOW_MS = 24 * 3600_000;
const TEST_LIMIT_PER_10_MIN = 5;
const SUB_COLUMNS = 'id, user_id, household_id, endpoint, p256dh, auth, tz, prefs, created_at, disabled_at, user_agent';

type Sub = SubscriptionRow & { user_agent: string | null };

Deno.serve(async (req: Request) => {
  if (req.method === 'OPTIONS') return new Response('ok', { headers: corsHeaders });
  if (req.method !== 'POST') return json({ error: 'method_not_allowed' }, 405);

  const admin = createClient(env('SUPABASE_URL'), env('SUPABASE_SERVICE_ROLE_KEY'));
  const body = await req.json().catch(() => ({})) as { mode?: string; endpoint?: string };
  const mode = new URL(req.url).searchParams.get('mode') ?? body.mode ?? '';
  const bearer = (req.headers.get('Authorization') ?? '').replace(/^Bearer\s+/i, '');

  if (mode === 'dispatch') {
    const given = req.headers.get('x-cron-secret') ?? '';
    const { data: cronOk } = given ? await admin.rpc('web_push_cron_ok', { p: given }) : { data: false };
    if (!cronOk && !(await isServiceCaller(bearer))) return json({ error: 'forbidden' }, 403);
    try {
      return json(await dispatch(admin, new Date()));
    } catch (e) {
      console.error('[web-push] dispatch failed', (e as Error)?.message);
      return json({ error: 'dispatch_failed' }, 500);
    }
  }

  const { data: { user }, error: aErr } = await admin.auth.getUser(bearer);
  if (aErr || !user) return json({ error: 'unauthorized' }, 401);

  if (mode === 'key') {
    const keys = await vapidKeys(admin);
    return json({ publicKey: keys.publicKey });
  }

  if (mode === 'test') {
    const since = new Date(Date.now() - 10 * 60_000).toISOString();
    const { count } = await admin.from('push_deliveries').select('id', { count: 'exact', head: true })
      .eq('user_id', user.id).eq('kind', 'test').gt('created_at', since);
    if ((count ?? 0) >= TEST_LIMIT_PER_10_MIN) return json({ error: 'too_many_tests' }, 429);
    let q = admin.from('push_subscriptions').select(SUB_COLUMNS).eq('user_id', user.id).is('disabled_at', null);
    if (body.endpoint) q = q.eq('endpoint', body.endpoint);
    const { data: subs, error } = await q;
    if (error) return json({ error: 'subscriptions_unavailable' }, 500);
    if (!subs?.length) return json({ error: 'no_devices' }, 404);
    const keys = await vapidKeys(admin);
    const now = new Date();
    const results = [];
    for (const sub of subs as Sub[]) {
      const outcome = await sendWebPush(sub, testPayload(now, sub.tz), keys, { ttlSeconds: 600, urgency: 'high' });
      await record(admin, sub, null, 'test', outcome);
      results.push({ device: deviceLabel(sub.user_agent), status: outcome.status, accepted: outcome.ok, gone: outcome.gone });
    }
    return json({ sent: results.length, results });
  }

  return json({ error: 'unknown_mode' }, 400);
});

/** The VAPID pair from Vault, created (once, race-safe) on first use. */
async function vapidKeys(admin: SupabaseClient): Promise<VapidKeys> {
  const { data } = await admin.rpc('web_push_vapid');
  if (data?.publicKey) return data as VapidKeys;
  const fresh = await generateVapidKeys(VAPID_SUBJECT);
  const { data: stored, error } = await admin.rpc('web_push_store_vapid', { p: fresh });
  if (error || !stored?.publicKey) throw new Error(`vapid_store_failed: ${error?.message ?? 'empty'}`);
  return stored as VapidKeys;   // whichever pair won a concurrent first use
}

async function record(
  admin: SupabaseClient, sub: Sub, notificationId: string | null, kind: 'test' | 'notification',
  outcome: { status: number; ok: boolean; gone: boolean; error?: string },
): Promise<void> {
  await admin.from('push_deliveries').insert({
    subscription_id: sub.id, user_id: sub.user_id, notification_id: notificationId, kind,
    status: outcome.status, error: outcome.error ?? null,
  });
  await admin.rpc('web_push_mark_device', { p_id: sub.id, p_status: outcome.status, p_ok: outcome.ok, p_gone: outcome.gone });
}

function deviceLabel(ua: string | null): string {
  const u = ua ?? '';
  const os = /Android/.test(u) ? 'Android' : /iPhone|iPad|iPod/.test(u) ? 'iPhone/iPad' : /Windows/.test(u) ? 'Windows'
    : /Mac OS X/.test(u) ? 'Mac' : /Linux/.test(u) ? 'Linux' : 'device';
  const br = /Edg\//.test(u) ? 'Edge' : /SamsungBrowser/.test(u) ? 'Samsung Internet' : /Chrome\//.test(u) ? 'Chrome'
    : /Firefox\//.test(u) ? 'Firefox' : /Safari\//.test(u) ? 'Safari' : 'browser';
  return `${br} on ${os}`;
}

async function dispatch(admin: SupabaseClient, now: Date) {
  const { data: subRows, error } = await admin.from('push_subscriptions').select(SUB_COLUMNS).is('disabled_at', null);
  if (error) throw new Error(`subscriptions: ${error.message}`);
  const subs = (subRows ?? []) as Sub[];
  const households = [...new Set(subs.map((s) => s.household_id))];
  if (!households.length) return { households: 0, raised: 0, pushed: 0, skipped: {} };

  // A device keeps receiving only while its person is still a member of that household.
  const { data: members } = await admin.from('memberships').select('household_id, user_id').in('household_id', households);
  const isMember = new Set(((members ?? []) as { household_id: string; user_id: string }[]).map((m) => `${m.household_id}:${m.user_id}`));

  // 1. Raise what the app would raise.
  let raised = 0;
  const problems: string[] = [];
  for (const hid of households) {
    try {
      const owner = subs.find((s) => s.household_id === hid)!;
      const rows = await loadHouseholdRows(admin, owner.user_id, hid);
      const { data: keys } = await admin.from('notifications').select('dedupe_key').eq('household_id', hid);
      const fresh = notificationsOnServer(rows, ((keys ?? []) as { dedupe_key: string }[]).map((k) => k.dedupe_key), hid);
      if (fresh.length) {
        const { error: insErr } = await admin.from('notifications')
          .upsert(fresh, { onConflict: 'household_id,dedupe_key', ignoreDuplicates: true });
        if (insErr) throw new Error(`insert: ${insErr.message}`);
        raised += fresh.length;
      }
    } catch (e) {
      problems.push(`${hid}: ${(e as Error)?.message ?? String(e)}`);   // one household never stops the rest
    }
  }

  // 2. Push what is new.
  const since = new Date(now.getTime() - PUSH_WINDOW_MS).toISOString();
  const { data: pending, error: pErr } = await admin.from('notifications')
    .select('id, household_id, type, priority, title, body, status, created_at, deep_link, dedupe_key')
    .in('household_id', households).is('pushed_at', null).gt('created_at', since).order('created_at');
  if (pErr) throw new Error(`pending: ${pErr.message}`);
  const keys = pending?.length ? await vapidKeys(admin) : null;
  let pushed = 0;
  const skipped: Record<string, number> = {};
  for (const n of (pending ?? []) as NotificationRow[]) {
    for (const sub of subs) {
      if (sub.household_id !== n.household_id) continue;
      if (!isMember.has(`${sub.household_id}:${sub.user_id}`)) { skipped.not_a_member = (skipped.not_a_member ?? 0) + 1; continue; }
      const why = skipReason(n, sub, now);
      if (why) { skipped[why] = (skipped[why] ?? 0) + 1; continue; }
      if (!isPushEndpoint(sub.endpoint)) { skipped.endpoint_not_allowed = (skipped.endpoint_not_allowed ?? 0) + 1; continue; }
      // W0 (BE-FN-07) — one device's failure never stops the others.
      try {
        const outcome = await sendWebPush(sub, payloadFor(n), keys!, { urgency: 'high' });
        await record(admin, sub, n.id, 'notification', outcome);
        if (outcome.ok) pushed++;
        if (outcome.gone) sub.disabled_at = now.toISOString();
      } catch (e) {
        skipped.send_error = (skipped.send_error ?? 0) + 1;
        problems.push(`push ${sub.id ?? '?'}: ${(e as Error)?.message ?? String(e)}`.slice(0, 300));
      }
    }
  }
  // 3. Every row considered is done, pushed or deliberately not.
  const ids = ((pending ?? []) as NotificationRow[]).map((n) => n.id);
  if (ids.length) await admin.from('notifications').update({ pushed_at: now.toISOString() }).in('id', ids);
  return { households: households.length, raised, considered: ids.length, pushed, skipped, problems };
}
