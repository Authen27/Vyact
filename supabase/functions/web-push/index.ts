// web-push — lock-screen notifications for the installed app (v10.48.0, TD-22).
//
// Three callers, one function (deployed --no-verify-jwt; every mode checks its own auth):
//   • POST {mode:'key'}   member JWT → the VAPID public key the browser subscribes with.
//   • POST {mode:'test'}  member JWT → a test notification to the caller's own devices,
//                         with each push service's answer, so a device is proven end to end.
//   • v10.127.0 (T4d): a device is a browser (kind 'webpush', Web Push) or the Vyact Android app (kind
//     'fcm', Firebase Cloud Messaging through _shared/fcm.ts, with the service account in the secret
//     FCM_SERVICE_ACCOUNT_JSON). Both get the same payload under the same rules; without the secret a phone
//     is skipped as fcm_not_configured.
//   • POST ?mode=dispatch pg_cron (x-cron-secret, checked against Vault) or the service key:
//       1. for every household with a subscribed device, raise the notifications the APP
//          would raise (the bundled lib/notifications.ts rules, serverEngine) into the
//          shared `notifications` table, so nobody needs the app open (v10.135.0: Pip's
//          nudges too, within their allowance of one a day and three a week);
//       2. push every unread, not-yet-pushed P1 notification to the household's devices,
//          subject to each device's own switches and quiet hours (web-push-rules.ts), and
//          Pip's nudges (P2) to the devices that turned "Pip's nudges" on;
//       3. stamp `pushed_at`, log each attempt in `push_deliveries`, and retire devices the
//          push service reports gone (404/410).
//
// Keys: the VAPID key pair is generated here on first use and kept in Vault
// (web_push_vapid); the cron secret is generated by the migration, also in Vault. No
// person ever sees or handles either.
import { createClient, type SupabaseClient } from 'https://esm.sh/@supabase/supabase-js@2.45.0';
import { env, json, corsHeaders } from '../_shared/whatsapp.ts';
import { isServiceCaller } from '../_shared/service-auth.ts';
import { withJobRun, type JobOutcome } from '../_shared/jobRuns.ts';
import { generateVapidKeys, sendWebPush, isPushEndpoint, type VapidKeys, type PushTarget } from '../_shared/web-push.ts';
import { parseServiceAccount, sendFcm, type ServiceAccount } from '../_shared/fcm.ts';
import {
  skipReason, payloadFor, testPayload, type SubscriptionRow, type NotificationRow, type PushPayload,
} from '../_shared/web-push-rules.ts';
import { loadHouseholdRows } from '../_shared/agent/householdLoader.ts';
import { notificationsOnServer, lockScreenTextOnServer } from '../_shared/agent/engine.ts';

const VAPID_SUBJECT = 'https://vyact.app';
/** Rows older than this are never pushed (a device that was offline gets today's news, not last week's). */
const PUSH_WINDOW_MS = 24 * 3600_000;
const TEST_LIMIT_PER_10_MIN = 5;
/** BE-FN-07 — households raised per run (they take turns), and the time a run may spend raising. */
const RAISE_PER_RUN = 50;
const RAISE_BUDGET_MS = 60_000;
const RUN_EVERY_MS = 15 * 60_000;   // the pg_cron schedule
/** Q7: Pip's rows read back for its allowance and its once-a-month keys (a month and a little). */
const PIP_LOOKBACK_MS = 40 * 86_400_000;
const SUB_COLUMNS = 'id, user_id, household_id, kind, fcm_token, endpoint, p256dh, auth, tz, prefs, created_at, disabled_at, user_agent';

type Sub = SubscriptionRow & { user_agent: string | null };
/** A send's answer. `deviceFault: false` = the fault was ours (FCM credentials, quota, outage): not the phone's. */
type Outcome = { status: number; ok: boolean; gone: boolean; error?: string; deviceFault?: boolean };

/** A browser row's push target (endpoint and keys), or null for a phone or a malformed row. */
function webTarget(sub: Sub): PushTarget | null {
  if (sub.kind === 'fcm' || !sub.endpoint || !sub.p256dh || !sub.auth) return null;
  return { endpoint: sub.endpoint, p256dh: sub.p256dh, auth: sub.auth };
}

/** The Firebase service account from the secret, or null (FCM off). */
const fcmAccount = (): ServiceAccount | null => parseServiceAccount(env('FCM_SERVICE_ACCOUNT_JSON'));

/** Sends one payload to one device of either kind; a reason string when it cannot be sent at all. */
async function deliver(
  sub: Sub, payload: PushPayload, keys: () => Promise<VapidKeys>, fcm: ServiceAccount | null,
  opts: { ttlSeconds?: number; urgency?: 'high' } = {},
): Promise<Outcome | 'fcm_not_configured' | 'endpoint_not_allowed'> {
  if (sub.kind === 'fcm') {
    if (!fcm || !sub.fcm_token) return 'fcm_not_configured';
    return await sendFcm(fcm, sub.fcm_token, payload);
  }
  const target = webTarget(sub);
  if (!target || !isPushEndpoint(target.endpoint)) return 'endpoint_not_allowed';
  return await sendWebPush(target, payload, await keys(), opts);
}

Deno.serve(async (req: Request) => {
  if (req.method === 'OPTIONS') return new Response('ok', { headers: corsHeaders });
  if (req.method !== 'POST') return json({ error: 'method_not_allowed' }, 405);

  const admin = createClient(env('SUPABASE_URL'), env('SUPABASE_SERVICE_ROLE_KEY'));
  const body = await req.json().catch(() => ({})) as { mode?: string; endpoint?: string; fcmToken?: string };
  const mode = new URL(req.url).searchParams.get('mode') ?? body.mode ?? '';
  const bearer = (req.headers.get('Authorization') ?? '').replace(/^Bearer\s+/i, '');

  if (mode === 'dispatch') {
    const given = req.headers.get('x-cron-secret') ?? '';
    const { data: cronOk } = given ? await admin.rpc('web_push_cron_ok', { p: given }) : { data: false };
    if (!cronOk && !(await isServiceCaller(bearer))) return json({ error: 'forbidden' }, 403);
    try {
      // Q4 (OPS-06): the run is recorded in job_runs (counts only).
      return json(await withJobRun(admin, 'web-push-dispatch', () => dispatch(admin, new Date()), dispatchOutcome));
    } catch (e) {
      console.error('[web-push] dispatch failed', (e as Error)?.message);
      return json({ error: 'dispatch_failed' }, 500);
    }
  }

  const { data: { user }, error: aErr } = await admin.auth.getUser(bearer);
  if (aErr || !user) return json({ error: 'unauthorized' }, 401);

  if (mode === 'key') {
    const keys = await vapidKeys(admin);
    return json({ publicKey: keys.publicKey });
  }

  if (mode === 'test') {
    const since = new Date(Date.now() - 10 * 60_000).toISOString();
    const { count } = await admin.from('push_deliveries').select('id', { count: 'exact', head: true })
      .eq('user_id', user.id).eq('kind', 'test').gt('created_at', since);
    if ((count ?? 0) >= TEST_LIMIT_PER_10_MIN) return json({ error: 'too_many_tests' }, 429);
    let q = admin.from('push_subscriptions').select(SUB_COLUMNS).eq('user_id', user.id).is('disabled_at', null);
    if (body.endpoint) q = q.eq('endpoint', body.endpoint);
    if (body.fcmToken) q = q.eq('fcm_token', body.fcmToken);
    const { data: subs, error } = await q;
    if (error) return json({ error: 'subscriptions_unavailable' }, 500);
    if (!subs?.length) return json({ error: 'no_devices' }, 404);
    let vapid: VapidKeys | null = null;
    const keys = async () => (vapid ??= await vapidKeys(admin));
    const fcm = fcmAccount();
    const now = new Date();
    const results = [];
    for (const sub of subs as Sub[]) {
      const device = deviceLabel(sub);
      // T2b-2 (BE-FN-07): one device's failure never stops the test for the others.
      try {
        const outcome = await deliver(sub, testPayload(now, sub.tz), keys, fcm, { ttlSeconds: 600, urgency: 'high' });
        if (typeof outcome === 'string') { results.push({ device, status: 0, accepted: false, gone: false, problem: outcome }); continue; }
        await record(admin, sub, null, 'test', outcome);
        results.push({ device, status: outcome.status, accepted: outcome.ok, gone: outcome.gone });
      } catch {
        results.push({ device, status: 0, accepted: false, gone: false });
      }
    }
    return json({ sent: results.length, results });
  }

  return json({ error: 'unknown_mode' }, 400);
});

/** The VAPID pair from Vault, created (once, race-safe) on first use. */
async function vapidKeys(admin: SupabaseClient): Promise<VapidKeys> {
  const { data } = await admin.rpc('web_push_vapid');
  if (data?.publicKey) return data as VapidKeys;
  const fresh = await generateVapidKeys(VAPID_SUBJECT);
  const { data: stored, error } = await admin.rpc('web_push_store_vapid', { p: fresh });
  if (error || !stored?.publicKey) throw new Error(`vapid_store_failed: ${error?.message ?? 'empty'}`);
  return stored as VapidKeys;   // whichever pair won a concurrent first use
}

async function record(
  admin: SupabaseClient, sub: Sub, notificationId: string | null, kind: 'test' | 'notification', outcome: Outcome,
): Promise<void> {
  await admin.from('push_deliveries').insert({
    subscription_id: sub.id, user_id: sub.user_id, notification_id: notificationId, kind,
    status: outcome.status, error: outcome.error ?? null,
  });
  // T4d: a fault of OURS (FCM credentials, quota, outage) is logged above but never counts against the phone,
  // or five bad runs would retire every phone (web_push_mark_device retires after five failures in a row).
  if (!outcome.ok && outcome.deviceFault === false) return;
  await admin.rpc('web_push_mark_device', { p_id: sub.id, p_status: outcome.status, p_ok: outcome.ok, p_gone: outcome.gone });
}

function deviceLabel(sub: { kind?: string; user_agent: string | null }): string {
  if (sub.kind === 'fcm') return 'Vyact app on Android';
  const u = sub.user_agent ?? '';
  const os = /Android/.test(u) ? 'Android' : /iPhone|iPad|iPod/.test(u) ? 'iPhone/iPad' : /Windows/.test(u) ? 'Windows'
    : /Mac OS X/.test(u) ? 'Mac' : /Linux/.test(u) ? 'Linux' : 'device';
  const br = /Edg\//.test(u) ? 'Edge' : /SamsungBrowser/.test(u) ? 'Samsung Internet' : /Chrome\//.test(u) ? 'Chrome'
    : /Firefox\//.test(u) ? 'Firefox' : /Safari\//.test(u) ? 'Safari' : 'browser';
  return `${br} on ${os}`;
}

/** Q4: a run's record. A household or a device that failed makes it partial. */
export function dispatchOutcome(r: Awaited<ReturnType<typeof dispatch>>): JobOutcome {
  const problems = ('problems' in r && r.problems) || [];
  const summary: JobOutcome['summary'] = { households: r.households, raised: r.raised, pushed: r.pushed, problems: problems.length };
  if ('considered' in r) Object.assign(summary, { considered: r.considered, deferred: r.deferred, raiseDeferred: r.raiseDeferred });
  for (const [why, n] of Object.entries(r.skipped as Record<string, number>)) summary[`skipped_${why}`] = n;
  return { status: problems.length ? 'partial' : 'ok', summary, error: problems[0] };
}

async function dispatch(admin: SupabaseClient, now: Date) {
  const { data: subRows, error } = await admin.from('push_subscriptions').select(SUB_COLUMNS).is('disabled_at', null);
  if (error) throw new Error(`subscriptions: ${error.message}`);
  const subs = (subRows ?? []) as Sub[];
  const households = [...new Set(subs.map((s) => s.household_id))];
  if (!households.length) return { households: 0, raised: 0, pushed: 0, skipped: {} };

  // A device keeps receiving only while its person is still a member of that household.
  const { data: members } = await admin.from('memberships').select('household_id, user_id').in('household_id', households);
  const isMember = new Set(((members ?? []) as { household_id: string; user_id: string }[]).map((m) => `${m.household_id}:${m.user_id}`));

  // 1. Raise what the app would raise.
  // v10.116.0 (T2b-2, audit DB-SEC-06): as the SERVER's own rows (`source = 'server'`). A device that wrote
  // the same notification first (same dedupe key) has its row taken over, with the server's wording
  // (raise_server_notifications), so a genuine push is never lost to a device's copy.
  // BE-FN-07: households take turns: at most RAISE_PER_RUN per run, starting where the last run's slot
  // points, and none once RAISE_BUDGET_MS has passed. The rest are raised on the next run (15 minutes).
  let raised = 0;
  let raiseDeferred = 0;
  const problems: string[] = [];
  const raiseStarted = Date.now();
  const offset = (Math.floor(now.getTime() / RUN_EVERY_MS) * RAISE_PER_RUN) % households.length;
  const turn = households.map((_, i) => households[(i + offset) % households.length]);
  for (const [index, hid] of turn.entries()) {
    if (index >= RAISE_PER_RUN || Date.now() - raiseStarted > RAISE_BUDGET_MS) { raiseDeferred++; continue; }
    try {
      const owner = subs.find((s) => s.household_id === hid)!;
      const rows = await loadHouseholdRows(admin, owner.user_id, hid);
      const { data: keys } = await admin.from('notifications').select('dedupe_key').eq('household_id', hid).eq('source', 'server');
      // Q7: Pip's rows from either source, with their dates (the nudge allowance and a device's own nudges).
      const { data: pipRows, error: pipErr } = await admin.from('notifications').select('dedupe_key, created_at')
        .eq('household_id', hid).like('dedupe_key', 'pip:%').gt('created_at', new Date(now.getTime() - PIP_LOOKBACK_MS).toISOString());
      if (pipErr) throw new Error(`pip rows: ${pipErr.message}`);
      const fresh = notificationsOnServer(rows, ((keys ?? []) as { dedupe_key: string }[]).map((k) => k.dedupe_key), hid,
        (pipRows ?? []) as { dedupe_key: string; created_at: string }[], now.getTime());
      if (fresh.length) {
        const { data: count, error: insErr } = await admin.rpc('raise_server_notifications', { p_rows: fresh });
        if (insErr) throw new Error(`raise: ${insErr.message}`);
        raised += Number(count ?? 0);
      }
    } catch (e) {
      problems.push(`${hid}: ${(e as Error)?.message ?? String(e)}`);   // one household never stops the rest
    }
  }

  // 2. Push what is new — only what the server raised (DB-SEC-06): a row a device wrote is never pushed.
  const since = new Date(now.getTime() - PUSH_WINDOW_MS).toISOString();
  const { data: pending, error: pErr } = await admin.from('notifications')
    .select('id, household_id, type, priority, title, body, status, created_at, deep_link, dedupe_key')
    .in('household_id', households).eq('source', 'server').is('pushed_at', null).gt('created_at', since).order('created_at');
  if (pErr) throw new Error(`pending: ${pErr.message}`);
  let vapid: VapidKeys | null = null;
  const keys = async () => (vapid ??= await vapidKeys(admin));
  const fcm = fcmAccount();
  // W3a (audit INT-TZC-05, BE-FN-08) — a push held back for QUIET HOURS is not done: it stays
  // pending (inside PUSH_WINDOW_MS) and goes out on the first run after quiet hours end. Before,
  // every row considered was stamped pushed, so a bill due today, raised at local midnight, was
  // never pushed at all. A device already reached for a row is not pushed again.
  const pendingIds = ((pending ?? []) as NotificationRow[]).map((n) => n.id);
  const reached = new Set<string>();
  if (pendingIds.length) {
    const { data: tried } = await admin.from('push_deliveries').select('notification_id, subscription_id')
      .in('notification_id', pendingIds);
    for (const t of (tried ?? []) as { notification_id: string; subscription_id: string }[]) {
      reached.add(`${t.notification_id}:${t.subscription_id}`);
    }
  }
  const waiting = new Set<string>();
  let pushed = 0;
  const skipped: Record<string, number> = {};
  for (const n of (pending ?? []) as NotificationRow[]) {
    for (const sub of subs) {
      if (sub.household_id !== n.household_id) continue;
      if (!isMember.has(`${sub.household_id}:${sub.user_id}`)) { skipped.not_a_member = (skipped.not_a_member ?? 0) + 1; continue; }
      if (reached.has(`${n.id}:${sub.id}`)) { skipped.already_pushed = (skipped.already_pushed ?? 0) + 1; continue; }
      const why = skipReason(n, sub, now);
      if (why === 'quiet_hours') waiting.add(n.id);
      if (why) { skipped[why] = (skipped[why] ?? 0) + 1; continue; }
      // W0 (BE-FN-07) — one device's failure never stops the others.
      try {
        // T4c (BE-FN-12): the device's "Show details on the lock screen" decides the words; T4d: browser or phone.
        const outcome = await deliver(sub, payloadFor(n, sub.prefs, lockScreenTextOnServer), keys, fcm, { urgency: 'high' });
        if (typeof outcome === 'string') { skipped[outcome] = (skipped[outcome] ?? 0) + 1; continue; }
        await record(admin, sub, n.id, 'notification', outcome);
        if (outcome.ok) pushed++;
        if (outcome.gone) sub.disabled_at = now.toISOString();
      } catch (e) {
        skipped.send_error = (skipped.send_error ?? 0) + 1;
        problems.push(`push ${sub.id ?? '?'}: ${(e as Error)?.message ?? String(e)}`.slice(0, 300));
      }
    }
  }
  // 3. A row is done once no device is still waiting for its quiet hours to end.
  const ids = pendingIds.filter((id) => !waiting.has(id));
  if (ids.length) await admin.from('notifications').update({ pushed_at: now.toISOString() }).in('id', ids);
  return { households: households.length, raised, raiseDeferred, considered: pendingIds.length, deferred: waiting.size, pushed, skipped, problems };
}
