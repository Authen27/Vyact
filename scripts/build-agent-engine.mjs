#!/usr/bin/env node
// Build the server copy of the Ask Vyact engine (W4, v10.45.0).
//
// Bundles react/src/lib/serverEngine.ts — and the app modules it imports — into
// supabase/functions/_shared/agent/engine.generated.js, so the WhatsApp webhook runs
// the SAME classify → resolve → phrase pipeline and the SAME money code as the app.
// One implementation: parity by construction, not by a hand port.
//
//   node scripts/build-agent-engine.mjs           write the bundle
//   node scripts/build-agent-engine.mjs --check   exit 1 if the committed bundle is stale
//
// Never edit the generated file by hand; change the app code and rebuild.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const entry = resolve(root, 'react/src/lib/serverEngine.ts');
const out = resolve(root, 'supabase/functions/_shared/agent/engine.generated.js');
const { rolldown } = await import(pathToFileURL(resolve(root, 'react/node_modules/rolldown/dist/index.mjs')).href);

// The browser Supabase client is reachable only through the in-app model transport
// (askVyactModelCall), which the server never uses — the webhook injects its own
// model call. Replace it with nothing rather than bundle a browser client.
const STUB = '\0vyact-no-browser-client';
const stubBrowserClient = {
  name: 'vyact-stub-browser-client',
  resolveId(source, importer) {
    if (source === './supabase' && importer && /[\\/]lib[\\/]askVyactModelCall\.ts$/.test(importer)) return STUB;
    return null;
  },
  load(id) {
    return id === STUB ? 'export const supabase = null;' : null;
  },
};

const bundle = await rolldown({
  input: entry,
  // Region comments carry paths relative to cwd: pin it so the bundle is byte-identical
  // wherever it is built (the gate compares it on Linux CI).
  cwd: root,
  platform: 'neutral',
  // Neutral ignores package "main" fields unless told; without this a dependency
  // (@dinero.js/currencies) stays an external import the edge cannot resolve.
  resolve: { mainFields: ['module', 'main'], conditionNames: ['import', 'module', 'default'] },
  plugins: [stubBrowserClient],
  logLevel: 'warn',
});
const { output } = await bundle.generate({ format: 'esm' });
await bundle.close();
const modules = Object.keys(output[0].modules)
  .map((m) => m.replace(/\\/g, '/').replace(/^.*?\/(react\/(?:src|node_modules)\/)/, '$1'))
  .filter((m) => !m.startsWith('\0'))
  .sort();

const header = [
  '// GENERATED by scripts/build-agent-engine.mjs — DO NOT EDIT.',
  '// The Ask Vyact engine from react/src/lib/serverEngine.ts, for the Edge runtime.',
  '// Rebuild: node scripts/build-agent-engine.mjs   (the gate runs it with --check)',
  '// Modules:',
  ...modules.map((m) => `//   ${m}`),
  '// @ts-nocheck',
  '',
].join('\n');
const code = header + output[0].code;

// Everything must be inside the bundle: the edge has no node_modules to import from.
const external = [...code.matchAll(/^import .* from ["']([^"']+)["'];?$/gm)].map((m) => m[1]);
if (external.length) {
  console.error(`✗ engine bundle still imports ${external.join(', ')} — it must be self-contained`);
  process.exit(1);
}

// A browser-only API in the bundle would fail at runtime on the edge, not at build.
// Matched as USE (a property access), not as a word: comments mention localStorage.
const BANNED = [/\blocalStorage\s*[.[]/, /\bsessionStorage\s*[.[]/, /\bindexedDB\s*\./, /\bdocument\s*\.\s*[a-z]/, /\bwindow\s*\.\s*[a-z]/, /import\.meta\.env/];
for (const banned of BANNED) {
  if (banned.test(code)) {
    console.error(`✗ engine bundle uses ${banned} — keep serverEngine's imports pure`);
    process.exit(1);
  }
}

if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== code.replace(/\r\n/g, '\n')) {
    console.error('✗ supabase/functions/_shared/agent/engine.generated.js is stale. Run: node scripts/build-agent-engine.mjs');
    process.exit(1);
  }
  console.log(`✓ engine bundle in sync (${modules.length} modules)`);
} else {
  writeFileSync(out, code);
  console.log(`✓ wrote ${out} (${modules.length} modules, ${code.length} bytes)`);
}
